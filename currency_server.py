"""MCP-сервер «Время» — время от начала дня и его пересчёт в другие единицы.

Отдельный MCP-сервер проекта. Основная задача — вернуть, сколько времени
прошло от НАЧАЛА ТЕКУЩЕГО ДНЯ (00:00:00) до ТЕКУЩЕГО МОМЕНТА, и уметь
пересчитать это значение в другие единицы:

  * time_since_midnight — время от начала дня в формате HH:MM:SS
                          (ведущие нули, например "09:05:03");
  * minutes             — то же время в формате МИНУТЫ:СЕКУНДЫ MM:SS
                          (ведущие нули, например "545:03");
  * hours               — то же время в ДЕСЯТИЧНЫХ часах HH.HHH
                          (три знака после точки, с округлением; напр. "9.084");
  * ping                — проверка живости сервера.

Значение берётся из локального времени машины (datetime.now()) — без сети и
без внешних зависимостей (только стандартная библиотека). Все три инструмента
считают одно и то же значение (секунды от полуночи) в разных форматах.

ВАЖНО: сервер назван по id «currency» в rtk_app/config.py (MCP_SERVERS) и
запускается из файла currency_server.py — так сохраняется совместимость со
ссылками композиции task5. Логика полностью заменена (валютный функционал
удалён).

Запуск (как stdio-подпроцесс MCP):
    python currency_server.py

Переключение проекта на этот сервер — в rtk_app/config.py (MCP_SERVERS).
"""

from datetime import datetime

from mcp.server.mcpserver import MCPServer

mcp = MCPServer("time")


# --------------------------------------------------------------------------
# Вспомогательные функции
# --------------------------------------------------------------------------
def _seconds_since_midnight(now=None):
    """Число секунд от начала текущего дня (00:00:00) до момента now.

    now — datetime (по умолчанию — текущее локальное время). Берём часы,
    минуты и секунды (микросекунды не учитываем).
    """
    now = now or datetime.now()
    return now.hour * 3600 + now.minute * 60 + now.second


# --------------------------------------------------------------------------
# Инструменты MCP
# --------------------------------------------------------------------------
@mcp.tool()
def ping() -> str:
    """Проверка живости сервера «Время»."""
    return "Время на связи."


@mcp.tool()
def time_since_midnight() -> str:
    """Время от начала текущего дня (00:00:00) до текущего момента.

    Возвращает строку формата HH:MM:SS с ВЕДУЩИМИ НУЛЯМИ,
    например "09:05:03" (9 часов 5 минут 3 секунды от начала суток).
    """
    secs = _seconds_since_midnight()
    h, rem = divmod(secs, 3600)
    m, s = divmod(rem, 60)
    return "%02d:%02d:%02d" % (h, m, s)


@mcp.tool()
def minutes() -> str:
    """Время от начала дня в формате МИНУТЫ:СЕКУНДЫ (MM:SS).

    То же значение, что и time_since_midnight, но в минутах и секундах:
    секунды с ВЕДУЩИМ НУЛЁМ, например "545:03" (545 минут 3 секунды).
    """
    secs = _seconds_since_midnight()
    m, s = divmod(secs, 60)
    return "%d:%02d" % (m, s)


@mcp.tool()
def hours() -> str:
    """Время от начала дня в ДЕСЯТИЧНЫХ часах (HH.HHH).

    То же значение, что и time_since_midnight, но в часах с ДРОБНОЙ частью:
    три знака после точки, с округлением, например "9.084" (9 часов 5 минут).
    """
    secs = _seconds_since_midnight()
    return "%.3f" % (secs / 3600.0)


if __name__ == "__main__":
    # Транспорт по умолчанию — stdio (как подпроцесс MCP-клиента проекта).
    mcp.run()
